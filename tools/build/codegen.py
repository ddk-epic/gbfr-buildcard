# Writes the exported objects' Ids as CardIds.g.cs.
OUTPUT = "gbfr.qol.buildcard/Generated/CardIds.g.cs"
DEPTH_TYPES = ["short", "short[]", "short[][]", "short[][][]", "short[][][][]", "short[][][][][]"]


def depth(value):
    return 1 + depth(value[0]) if isinstance(value, list) else 0


def literal(value, ids):
    if isinstance(value, list):
        return "[" + ", ".join(literal(v, ids) for v in value) + "]"
    return str(ids[value])


def nodes(value):
    if isinstance(value, list):
        for v in value:
            yield from nodes(v)
    else:
        yield value


def generate(prefab, exports):
    ids = prefab.ids()
    lines = ["// <auto-generated/>",
             "// Written by tools/build/build.py from status01; do not edit.",
             "namespace gbfr.qol.buildcard.Hooks;",
             "",
             "internal static class CardIds",
             "{"]
    for key, value in sorted(exports.items()):
        for node in nodes(value):
            if node not in ids:
                raise KeyError(f"{key}: {node.name} is not in status01")
        d = depth(value)
        if d == 0:
            lines.append(f"    public const short {key} = {ids[value]};")
        else:
            lines.append(f"    public static readonly {DEPTH_TYPES[d]} {key} = {literal(value, ids)};")
    lines.append("")
    lines.append(f"    public const int ObjectCount = {len(ids)};")
    lines.append("}")
    return "\n".join(lines) + "\n"
