# Writes the exported objects' Ids, records and constants as CardLayout.g.cs.
import json
import os
import sys

sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data"))
from hashing import xxhash32_custom  # noqa: E402

OUTPUT = "gbfr.qol.buildcard/Generated/CardLayout.g.cs"
FNV_OFFSET, FNV_PRIME = 0x811C9DC5, 0x01000193


class Record:
    # a C# readonly record struct; type "Section.Name", fields in declaration order
    def __init__(self, type_, **fields):
        self.type = type_
        self.fields = fields


class Hash:
    # a 32-bit hash, written as a uint
    def __init__(self, value):
        self.value = value


def yaml_string(text):
    # a YAML scalar's string, unquoted
    if len(text) >= 2 and text[0] == text[-1] == "'":
        return text[1:-1].replace("''", "'")
    if len(text) >= 2 and text[0] == text[-1] == '"':
        return json.loads(text)
    return text


def name_hash(node):
    # the game's hash of the node's name
    return xxhash32_custom(yaml_string(node.name))


def prefab_hash(ids):
    # FNV-1a over each object's Id and name hash, in Id order
    h = FNV_OFFSET
    for node, id_ in ids.items():
        for value in (id_, name_hash(node)):
            for byte in value.to_bytes(4, "little"):
                h = ((h ^ byte) * FNV_PRIME) & 0xFFFFFFFF
    return h


def split(key):
    section, _, name = key.rpartition(".")
    return section, name


def cs_type(value, records):
    if isinstance(value, Record):
        fields = {name: cs_type(v, records) for name, v in value.fields.items()}
        if records.setdefault(value.type, fields) != fields:
            raise TypeError(f"{value.type}: fields {fields} differ from {records[value.type]}")
        return split(value.type)[1]
    if isinstance(value, list):
        kinds = {cs_type(v, records) for v in value}
        if len(kinds) != 1:
            raise TypeError(f"a list of {sorted(kinds) or 'nothing'}")
        return kinds.pop() + "[]"
    if isinstance(value, Hash):
        return "uint"
    if isinstance(value, float):
        return "float"
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "uint" if value > 0x7FFFFFFF else "int"
    return "short"


def literal(value, ids, key):
    if isinstance(value, Record):
        return "new(" + ", ".join(literal(v, ids, key) for v in value.fields.values()) + ")"
    if isinstance(value, list):
        return "[" + ", ".join(literal(v, ids, key) for v in value) + "]"
    if isinstance(value, Hash):
        return f"0x{value.value:08X}"
    if isinstance(value, float):
        return f"{value}f"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if value not in ids:
        raise KeyError(f"{key}: {value.name} is not in status01")
    return str(ids[value])


def member(name, value, ids, records, key):
    kind = cs_type(value, records)
    if kind in ("short", "int", "uint", "float", "bool"):
        return f"public const {kind} {name} = {literal(value, ids, key)};"
    return f"public static readonly {kind} {name} = {literal(value, ids, key)};"


def generate(prefab, exports):
    ids = prefab.ids()
    exports = dict(exports)
    exports["Status01.ObjectCount"] = len(ids)
    exports["Status01.PrefabHash"] = Hash(prefab_hash(ids))

    records = {}
    sections = {}
    for key, value in sorted(exports.items()):
        section, name = split(key)
        sections.setdefault(section, []).append(member(name, value, ids, records, key))
    for type_, fields in records.items():
        section, name = split(type_)
        params = ", ".join(f"{kind} {field}" for field, kind in fields.items())
        sections.setdefault(section, []).insert(0, f"public readonly record struct {name}({params});")

    lines = ["// <auto-generated/>",
             "// Written by tools/build/build.py from status01; do not edit.",
             "namespace gbfr.qol.buildcard;",
             "",
             "internal static class CardLayout",
             "{"]
    for i, (section, members) in enumerate(sorted(sections.items())):
        if i:
            lines.append("")
        indent = "    "
        if section:
            lines.append(f"    public static class {section}")
            lines.append("    {")
            indent = "        "
        lines.extend(indent + m for m in members)
        if section:
            lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"
